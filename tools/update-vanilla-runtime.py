#!/usr/bin/env python3
"""Pin the official client and library downloads for the configured Minecraft version."""

import hashlib
import json
from pathlib import Path
import re
import urllib.request


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def main():
    root = Path(__file__).resolve().parent.parent
    catalog = (root / "gradle/libs.versions.toml").read_text()
    version = re.search(r'^minecraft = "([^"]+)"$', catalog, re.MULTILINE).group(1)
    manifest = json.loads(fetch("https://piston-meta.mojang.com/mc/game/version_manifest_v2.json"))
    entry = next(entry for entry in manifest["versions"] if entry["id"] == version)
    version_bytes = fetch(entry["url"])
    if hashlib.sha1(version_bytes).hexdigest() != entry["sha1"]:
        raise ValueError("Version manifest SHA-1 mismatch")
    metadata = json.loads(version_bytes)
    artifacts = [("minecraft-client:" + version, metadata["downloads"]["client"], "")]
    for library in metadata["libraries"]:
        download = library.get("downloads", {}).get("artifact")
        if download is None:
            raise ValueError("Library has no downloadable artifact: " + library["name"])
        rules = library.get("rules", [])
        os_name = ""
        if rules:
            # Fail on new rule forms rather than silently generating the wrong classpath.
            if len(rules) != 1 or rules[0].get("action") != "allow" or set(rules[0]) != {"action", "os"}:
                raise ValueError("Unsupported library rules: " + repr(rules))
            if set(rules[0]["os"]) != {"name"}:
                raise ValueError("Unsupported OS rules: " + repr(rules))
            os_name = rules[0]["os"]["name"]
        artifacts.append((library["name"], download, os_name))
    lines = [
        "# Generated by tools/update-vanilla-runtime.py from Mojang's version manifest.",
        "# These are download coordinates and checksums, not redistributed game files.",
        f"version={version}",
        f"java.version={metadata['javaVersion']['majorVersion']}",
        f"artifact.count={len(artifacts)}",
    ]
    for index, (name, download, os_name) in enumerate(artifacts):
        for key, value in {"name": name, "url": download["url"], "sha1": download["sha1"],
                           "size": download["size"], "os": os_name}.items():
            lines.append(f"artifact.{index}.{key}={value}")
    destination = root / "vanilla-runtime/src/main/resources/vanilla-runtime.properties"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n")
    print(f"Pinned Minecraft {version} and {len(artifacts) - 1} library artifacts")


if __name__ == "__main__":
    main()
